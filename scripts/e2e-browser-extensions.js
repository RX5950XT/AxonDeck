const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const http = require('node:http')
const { app, BrowserWindow, session, ipcMain, protocol } = require('electron')
const { tempDir } = require('./lib/test-temp')
const DATA = tempDir('e-'), ROOT = process.env.AXONDECK_ASAR || path.join(__dirname, '..')
const SC = 'ndcooeababalnlpkfedmmbbbgkljhpjf'
app.setPath('userData', DATA)
protocol.registerSchemesAsPrivileged([require(path.join(ROOT,'src/main/browser-extension-manager')).PRIVILEGES])
