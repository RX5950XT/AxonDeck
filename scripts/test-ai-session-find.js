'use strict'
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const vm = require('node:vm')
const source = fs.readFileSync(path.join(__dirname, '../src/renderer/scripts/ws-ai-session-find.js'), 'utf8').replace(/^export /gm, '')
const { findTextMatches, sessionTitleExcerpt } = vm.runInNewContext(`${source}\n;({findTextMatches, sessionTitleExcerpt})`)
const matches = (text, query) => JSON.parse(JSON.stringify(findTextMatches(text, query)))
assert.deepEqual(matches('Codex codex CODEX', 'codex'), [[0, 5], [6, 11], [12, 17]])
assert.deepEqual(matches('第一行\n工具 [a.*] 尾巴', '[a.*]'), [[7, 12]], '搜尋字元照原文，不當作 regex')
assert.deepEqual(matches('İ 😀工具 😀工具', '😀工具'), [[2, 6], [7, 11]], 'Unicode 保留原文位置')
assert.deepEqual(matches('aaaa', 'aa'), [[0, 2], [2, 4]])
assert.deepEqual(matches('任意', ''), [])
assert.deepEqual(matches('工具\n完整內容', '工具\n完整'), [[0, 5]])
assert.equal(sessionTitleExcerpt('短標題\n第二行'), '短標題 第二行')
const title = '😀長標題'.repeat(100)
assert.ok([...sessionTitleExcerpt(title)].length <= 41)
assert.ok(sessionTitleExcerpt(title).endsWith('…'))
assert.equal(title, '😀長標題'.repeat(100), '不修改完整標題')
console.log('PASS AI 紀錄搜尋：大小寫、literal、Unicode、換行、空搜尋與長標題摘要')
