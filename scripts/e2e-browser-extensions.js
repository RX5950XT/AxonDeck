  if (!popup.isDestroyed()) popup.destroy()
  popup = await page(ses, 'chrome-extension://' + SC + '/src/popup.html')
  await wait(() => js(popup, 'document.body.innerText.includes("尚未啟用")'), 'disabled scripts warning')
  assert.equal(JSON.parse(fs.readFileSync(path.join(dir,'extension-state.json')))[SC].userScripts, false)
  await service.change(SC, 'userScripts', true)
  if (!popup.isDestroyed()) popup.destroy()
  popup = await page(ses, 'chrome-extension://' + SC + '/src/popup.html')
  await wait(() => js(popup, 'chrome.userScripts.getScripts().then(s=>s.length>=4)'), 'restored script permission')
