'use strict'
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const Module = require('node:module')
const { tempDir } = require('./lib/test-temp')

const root = tempDir('pack-preview-data-')
const built = path.join(root, 'built'), preview = path.join(root, 'preview'), models = path.join(root, 'models')
fs.mkdirSync(path.join(built, 'resources'), { recursive: true })
fs.mkdirSync(path.join(preview, 'resources'), { recursive: true })
fs.mkdirSync(path.join(preview, 'user-data'))
fs.mkdirSync(models)
fs.writeFileSync(path.join(built, 'resources', 'app.asar'), 'new archive')
fs.writeFileSync(path.join(preview, 'resources', 'app.asar'), 'old archive')
fs.writeFileSync(path.join(preview, 'user-data', 'terminals.json'), 'saved sessions')
fs.writeFileSync(path.join(models, 'model.gguf'), 'existing model')
fs.symlinkSync(models, path.join(preview, 'user-data', 'models'), 'junction')
const filename = path.join(__dirname, 'pack-preview.js')
const source = fs.readFileSync(filename, 'utf8').replace("const PREVIEW = path.join(ROOT, 'dist', 'win-unpacked')", `const PREVIEW = ${JSON.stringify(preview)}`)
const mod = new Module(filename, module)
mod.filename = filename; mod.paths = Module._nodeModulePaths(__dirname)
mod._compile(source + '\nmodule.exports.syncPreview = syncPreview', filename)
mod.exports.syncPreview(built)
assert.equal(fs.readFileSync(path.join(preview, 'user-data', 'terminals.json'), 'utf8'), 'saved sessions')
assert.equal(fs.readFileSync(path.join(models, 'model.gguf'), 'utf8'), 'existing model')
assert.equal(fs.readFileSync(path.join(preview, 'resources', 'app.asar'), 'utf8'), 'new archive')
console.log('PASS 更新預覽保留 user-data 與 junction 對面的真實模型')
